function hasBudgetInQuery(query: string): boolean {
  return /до\s*\d[\d\s]*[₽$]?/.test(query.toLowerCase())
}

/** Бюджетные ступени под категорию — считаем по реальным ценам её товаров. */
function categoryBudget(spec: ReturnType<typeof findCategorySpec>): string[] {
  const fallback = ['до 3 000 ₽', '3 000–7 000 ₽', '7 000–15 000 ₽', '15 000–30 000 ₽', 'от 30 000 ₽']
  if (!spec || !spec.items.length) return fallback
  const prices = spec.items.map((i) => i.price).sort((a, b) => a - b)
  const min = prices[0]
  const max = prices[prices.length - 1]
  const span = max - min
  if (max <= 5000) return ['до 2 000 ₽', '2 000–3 500 ₽', '3 500–5 000 ₽', 'от 5 000 ₽']
  if (max <= 10000) return ['до 4 000 ₽', '4 000–6 500 ₽', '6 500–9 000 ₽', 'от 9 000 ₽']
  if (max <= 20000) return ['до 6 000 ₽', '6 000–10 000 ₽', '10 000–16 000 ₽', 'от 16 000 ₽']
  if (max <= 40000) return ['до 12 000 ₽', '12 000–20 000 ₽', '20 000–30 000 ₽', 'от 30 000 ₽']
  if (span / min < 0.4) return [`до ${Math.round(min * 0.85 / 1000) * 1000} ₽`, `${Math.round(min / 1000) * 1000}–${Math.round(max / 1000) * 1000} ₽`, `от ${Math.round(max / 1000) * 1000} ₽`, 'Бюджет не ограничен']
  return ['до 20 000 ₽', '20 000–40 000 ₽', '40 000–70 000 ₽', 'от 70 000 ₽']
}

function buildCategory(query: string): Question[] {
  const spec = findCategorySpec(query)
  const qs = (spec && CATEGORY_QUESTIONS[spec.label]) || FALLBACK_CATEGORY
  const list = [qs.use, qs.detail]
  if (!hasBudgetInQuery(query)) {
    list.push({
      id: 'budget',
      title: 'На какой бюджет рассчитываете?',
      options: categoryBudget(spec),
    })
  }
  return list
}

