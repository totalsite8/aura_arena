function buildService(query: string): Question[] {
  const niche = findNiche(query)
  const priority = SERVICE_PRIORITY[niche.label] ?? ['Цена', 'Сроки', 'Гарантия', 'Отзывы']

  return [
    { id: 'work', title: 'Какой объём нужен?', options: niche.question1Options },
    {
      id: 'when',
      title: 'Когда нужно сделать?',
      options: ['Как можно скорее', 'В течение пары недель', 'В течение месяца', 'Пока присматриваюсь'],
    },
    {
      id: 'budget',
      title: 'На какую сумму рассчитываете?',
      options: budgetOptions(niche.min, niche.max),
    },
    { id: 'priority', title: 'Что для вас главное?', options: priority },
  ]
}

function budgetOptions(min: number, max: number): string[] {
  const k = (n: number) => `${Math.round(n / 1000)} 000 ₽`
  if (max < 10000) {
    return [`до ${k(min * 1.2)}`, `${k(min * 1.2)}–${k(max * 0.8)}`, 'Не знаю — посчитайте']
  }
  if (max > 100000) {
    return [`до ${k(max * 0.5)}`, `${k(max * 0.5)}–${k(max)}`, 'Не знаю — посчитайте']
  }
  return [`до ${k(min * 1.4)}`, `${k(min * 1.4)}–${k(max)}`, `от ${k(max)}`, 'Не знаю — посчитайте']
}

/* --------------------------------- API --------------------------------- */

export function buildQuestions(type: QueryType, query: string): Question[] {
  if (type === 'exact_product') return []
  if (type === 'category_search') return buildCategory(query)
  if (type === 'gift_search') return buildGift()
  return buildService(query)
}

/** Достаёт первую сумму из ответа-бюджета (₽), чтобы фильтровать по ней. */
export function budgetFromAnswer(answer: string | undefined): number | null {
  if (!answer) return null
  const m = answer.match(/\d[\d\s]*/)
  if (!m) return null
  const n = parseInt(m[0].replace(/\s/g, ''), 10)
  return Number.isFinite(n) && n > 0 ? n : null
}
